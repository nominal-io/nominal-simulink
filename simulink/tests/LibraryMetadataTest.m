classdef LibraryMetadataTest < BlocksetTestCase
%LIBRARYMETADATATEST  The library carries what makes it a published blockset.
%
%   None of this affects whether the block runs, so nothing else would notice it going
%   missing: the library would simply drop out of the Library Browser, or saved models
%   would stop following renames, with no error anywhere.

    methods (TestMethodSetup)
        function loadLibrary(~)
            load_system('nominal_lib');
        end
    end

    methods (Test)
        function isListedInTheLibraryBrowser(tc)
            % Both halves: slblocks names the library, and the library was saved with
            % the repository flag on. Either missing and the Browser shows nothing.
            %
            % Ours, not whichever slblocks is first on the path: the current folder
            % takes precedence over the path.
            tc.applyFixture(matlab.unittest.fixtures.CurrentFolderFixture( ...
                BlocksetTestCase.folder('library')));
            s = slblocks;
            tc.verifyEqual(s.Browser.Library, 'nominal_lib');
            tc.verifyEqual(s.Browser.Name, 'Nominal');
            tc.verifyEqual(get_param('nominal_lib', 'EnableLBRepository'), 'on');
        end

        function versionIsPinnedToTheVersionFile(tc)
            % Forwarding table entries compare against this, so it must not drift back to
            % the 1.0 an auto-incremented library would read after every rebuild.
            file = fullfile(fileparts(fileparts(mfilename('fullpath'))), 'VERSION');
            v = regexp(strtrim(fileread(file)), '^(\d+)\.(\d+)', 'tokens', 'once');
            tc.verifyEqual(get_param('nominal_lib', 'ModelVersion'), strjoin(v, '.'));
        end

        function linksCannotBeDisabled(tc)
            tc.verifyEqual(get_param('nominal_lib', 'LockLinksToLibrary'), 'on');
        end

        function quickInsertFindsTheBlock(tc)
            k = get_param('nominal_lib/Nominal Stream Sink', 'BlockKeywords');
            tc.verifyTrue(any(strcmp(string(k), "Nominal")));
        end

        function helpOpensTheBlockPage(tc)
            blk = 'nominal_lib/Nominal Stream Sink';
            tc.verifySubstring(get_param(blk, 'MaskHelp'), 'nominal_help(gcb)');

            % The page itself is generated by `just docs`, which this suite does not
            % need, so only follow the link through when the docs exist.
            tc.assumeTrue(isfile(fullfile(BlocksetTestCase.folder('doc'), 'html', ...
                                          'nominal_blockset.html')), ...
                          'docs not built');
            tc.verifyEqual(nominal_help(blk), ...
                fullfile(BlocksetTestCase.folder('doc'), 'html', 'nominal_stream_sink.html'));
        end
    end
end
